// ENEMY DAMAGE CALCULATION FUNCTION
int Enemy::damage(){
  float totaldmg = 0;
  totaldmg += enemy.strength;
  if (type == 'e'){
    totaldmg += ((10 - player.magicskill)/2);
  }
  else if (type == 'o'){
    totaldmg += ((10 - player.strength)/2);
  }
  if (crit()){
    totaldmg *= 1.5;
  }
  if (player.shield){
    int shieldhp = player.shieldhealth;
    player.shieldhealth -= totaldmg;
    if (player.shieldhealth <= 0){
      player.shieldhealth = 0;
      player.shield = false;
    }
    totaldmg = 0;
    std::cout << "\n Shield blocked incoming damage\n\n";
  }
  if ((rand() % 10) <= 1){
    totaldmg = 0;
  }
  return (int)round(totaldmg);
}
